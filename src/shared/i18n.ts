export function translate(locale: Locale, message: string, ...values: (string | number)[]): string {
  const template = locale === 'zh-cn' ? zhCN[message] || message : message;
  return template.replace(/\{(\d+)\}/g, (_, index: string) => String(values[Number(index)] ?? `{${index}}`));
}
